function setText(selector, value) {
  const element = document.querySelector(selector);
  if (element && value !== undefined) {
    element.textContent = value;
  }
}

function setTexts(selector, values) {
  document.querySelectorAll(selector).forEach((element, index) => {
    if (values[index] !== undefined) {
      element.textContent = values[index];
    }
  });
}

function setLanguage(lang) {
  const language = translations[lang] ? lang : "en";
  const t = translations[language];

  document.documentElement.lang = language;

  try {
    localStorage.setItem("sealroll-language", language);
  } catch (error) {
    console.warn("Language preference could not be saved.");
  }

  // Navigation
  setTexts(".nav nav a", t.nav);

  // Hero
  setText(".hero-copy .eyebrow", t.heroEyebrow);
  setText(".hero-copy h1", t.heroTitle);
  setText(".hero-copy .lead", t.heroLead);
  setTexts(".hero-copy .actions a", [
    t.contactButton,
    t.exploreButton
  ]);
  setText(".hero-brand p", t.heroTag);

  // Statement
  setText(".statement p", t.statement);

  // Solutions
  setText("#solutions .eyebrow", t.solutionsEyebrow);
  setText("#solutions h2", t.solutionsTitle);
  setTexts("#solutions .card h3", t.solutionTitles);
  setTexts("#solutions .card p", t.solutionDescriptions);

  // Technology
  setText("#technology .eyebrow", t.technologyEyebrow);
  setText("#technology h2", t.technologyTitle);
  setText("#technology > div:nth-child(2) > p", t.technologyText);
  setTexts("#technology .ticks li", t.benefits);

  // Technopreneurship Recognition
  setText("#recognition-eyebrow", t.recognitionEyebrow);
  setText("#recognition-title", t.recognitionTitle);
  setText("#recognition-description", t.recognitionDescription);
  setText("#recognition-certificate", t.recognitionCertificate);
  setText("#recognition-date", t.recognitionDate);

  // Applications
  setText("#applications .eyebrow", t.applicationsEyebrow);
  setText("#applications h2", t.applicationsTitle);
  setTexts("#applications .application-grid h3", t.applicationTitles);
  setTexts("#applications .application-grid p", t.applicationDescriptions);

  // Capabilities
  setText(".capabilities .eyebrow", t.capabilitiesEyebrow);
  setText(".capabilities h2", t.capabilitiesTitle);
  setTexts(".capabilities .chips span", t.chips);

  // About
  setText("#about .eyebrow", t.aboutEyebrow);
  setText("#about h2", t.aboutTitle);
  setText("#about .about-box p", t.aboutText);

  // Contact
  setText("#contact .eyebrow", t.contactEyebrow);
  setText("#contact h2", t.contactTitle);
  setText(
    "#contact .contact-card > span:first-of-type",
    t.founderTitle
  );
  setText(
    "#contact .contact-card > span:last-of-type",
    t.location
  );

  // Footer
  setText(
    "footer div span:last-child",
    "info@sealroll.com • +90 537 936 3002 • " + t.footerLocation
  );

  // Language buttons
  document.querySelectorAll(".lang-btn").forEach(button => {
    const active = button.dataset.lang === language;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", String(active));
  });

  // Page title and description
  document.title = t.pageTitle;

  const description = document.querySelector(
    'meta[name="description"]'
  );

  if (description) {
    description.content = t.pageDescription;
  }

  const ogTitle = document.querySelector(
    'meta[property="og:title"]'
  );

  if (ogTitle) {
    ogTitle.content = t.pageTitle;
  }

  const ogDescription = document.querySelector(
    'meta[property="og:description"]'
  );

  if (ogDescription) {
    ogDescription.content = t.pageDescription;
  }
}

document.addEventListener("DOMContentLoaded", () => {
  let savedLanguage = "en";

  try {
    savedLanguage =
      localStorage.getItem("sealroll-language") || "en";
  } catch (error) {
    savedLanguage = "en";
  }

  setLanguage(savedLanguage);

  document.querySelectorAll(".lang-btn").forEach(button => {
    button.addEventListener("click", () => {
      setLanguage(button.dataset.lang);
    });
  });
});

